"""A library of music beds the person keeps on the server and picks for a film.

Tracks live under ``runtime/bgm`` with an index that says what each one is: a
name, a mood, how long it runs. Uploads are checked by their bytes, not their
extension; a track generated by stage 6 can be kept here so the next project
can use it too. The timeline refers to a track by id, and the compositor gets
its path.
"""

from __future__ import annotations

import json
import re
import threading
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from app import settings

MAX_BGM_UPLOAD_BYTES = 20 * 1024 * 1024
_SIGNATURES = {
    "audio/mpeg": ((b"ID3",), (b"\xff\xfb", b"\xff\xf3", b"\xff\xf2"), ".mp3"),
    "audio/wav": ((b"RIFF",), (), ".wav"),
    "audio/x-wav": ((b"RIFF",), (), ".wav"),
    "audio/mp4": ((), (), ".m4a"),
    "audio/x-m4a": ((), (), ".m4a"),
    "audio/aac": ((b"\xff\xf1", b"\xff\xf9"), (), ".aac"),
    "audio/ogg": ((b"OggS",), (), ".ogg"),
}
_lock = threading.Lock()


class BgmUploadError(ValueError):
    pass


def library_dir() -> Path:
    return settings.RUNTIME_DIR / "bgm"


def _index_path() -> Path:
    return library_dir() / "index.json"


def _read_index() -> list[dict[str, Any]]:
    path = _index_path()
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    return [item for item in (data.get("items") or []) if isinstance(item, dict)] if isinstance(data, dict) else []


def _write_index(items: list[dict[str, Any]]) -> None:
    library_dir().mkdir(parents=True, exist_ok=True)
    _index_path().write_text(json.dumps({"items": items}, ensure_ascii=False, indent=2), encoding="utf-8")


def _probe_seconds(path: Path) -> float | None:
    from app.core.media_compositor import _probe_duration

    try:
        return _probe_duration(str(path))
    except Exception:  # noqa: BLE001 - duration is a nicety, not a requirement
        return None


def validate_audio_upload(filename: str, content_type: str, content: bytes) -> tuple[str, str]:
    """The declared type and the suffix to store under; raises when the bytes do not match."""
    if not content or len(content) > MAX_BGM_UPLOAD_BYTES:
        raise BgmUploadError("音频为空或超过 20MB")
    declared = (content_type or "").split(";", 1)[0].strip().lower()
    if declared not in _SIGNATURES:
        raise BgmUploadError("仅支持 MP3、WAV、M4A、AAC、OGG 音频")
    starts, frames, suffix = _SIGNATURES[declared]
    if declared in ("audio/mp4", "audio/x-m4a"):
        if len(content) < 12 or content[4:8] != b"ftyp":
            raise BgmUploadError("M4A 文件头无效")
    elif declared == "audio/wav" or declared == "audio/x-wav":
        if not content.startswith(b"RIFF") or content[8:12] != b"WAVE":
            raise BgmUploadError("WAV 文件头无效")
    elif not (any(content.startswith(s) for s in starts) or any(content.startswith(f) for f in frames)):
        raise BgmUploadError("音频内容与声明类型不一致")
    given = Path(filename or "").suffix.lower()
    if given and given not in {suffix, ".mp3" if declared == "audio/mpeg" else suffix}:
        raise BgmUploadError("文件扩展名与媒体类型不一致")
    return declared, suffix


def list_tracks() -> list[dict[str, Any]]:
    with _lock:
        items = _read_index()
    alive = []
    for item in items:
        path = library_dir() / str(item.get("file") or "")
        if path.is_file():
            alive.append({**item, "path": str(path)})
    return alive


def get_track(track_id: str) -> dict[str, Any] | None:
    return next((item for item in list_tracks() if item.get("id") == track_id), None)


def add_track(*, name: str, mood: str, content: bytes, filename: str, content_type: str, owner_id: str | None = None) -> dict[str, Any]:
    _, suffix = validate_audio_upload(filename, content_type, content)
    clean_name = re.sub(r"\s+", " ", (name or Path(filename or "").stem or "未命名配乐")).strip()[:80]
    track_id = uuid.uuid4().hex[:12]
    file_name = f"{track_id}{suffix}"
    with _lock:
        library_dir().mkdir(parents=True, exist_ok=True)
        (library_dir() / file_name).write_bytes(content)
        items = _read_index()
        item = {
            "id": track_id, "name": clean_name, "mood": (mood or "").strip()[:40], "file": file_name,
            "seconds": _probe_seconds(library_dir() / file_name), "bytes": len(content),
            "source": "upload", "owner_id": owner_id, "added_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }
        items.append(item)
        _write_index(items)
    return {**item, "path": str(library_dir() / file_name)}


def keep_generated(*, name: str, mood: str, source_path: str, owner_id: str | None = None) -> dict[str, Any]:
    """Keep a bed stage 6 generated, so another project can pick it."""
    source = Path(source_path)
    if not source.is_file():
        raise BgmUploadError("生成的配乐文件不存在")
    content = source.read_bytes()
    suffix = source.suffix.lower() or ".mp3"
    track_id = uuid.uuid4().hex[:12]
    file_name = f"{track_id}{suffix}"
    with _lock:
        library_dir().mkdir(parents=True, exist_ok=True)
        (library_dir() / file_name).write_bytes(content)
        items = _read_index()
        item = {
            "id": track_id, "name": (name or source.stem)[:80], "mood": (mood or "")[:40], "file": file_name,
            "seconds": _probe_seconds(library_dir() / file_name), "bytes": len(content),
            "source": "generated", "owner_id": owner_id, "added_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }
        items.append(item)
        _write_index(items)
    return {**item, "path": str(library_dir() / file_name)}


def remove_track(track_id: str) -> bool:
    with _lock:
        items = _read_index()
        keep = [item for item in items if item.get("id") != track_id]
        if len(keep) == len(items):
            return False
        gone = next(item for item in items if item.get("id") == track_id)
        try:
            (library_dir() / str(gone.get("file") or "")).unlink()
        except OSError:
            pass
        _write_index(keep)
    return True


__all__ = ["MAX_BGM_UPLOAD_BYTES", "BgmUploadError", "add_track", "get_track", "keep_generated", "library_dir", "list_tracks", "remove_track", "validate_audio_upload"]
