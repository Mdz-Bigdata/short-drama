def _table(scene_id: str) -> str:
    return "\n".join(
        f"| {index} | {size} | {angle} | {motion} | {desc} | | 环境声 | 3s | 线索 | {cast} | {scene_id} 办公室 |"
        for index, (size, angle, motion, desc, cast) in enumerate(ROWS, start=1)
    )


def _task(task_id: str = "spatial-1") -> Dict[str, Any]:
    return {
        "task_id": task_id,
        "owner_user_id": "director-user",
        "current_stage": 4,
        "status": "idle",
        "config": {"llm_model": "m", "image_model": "img", "video_model": "v", "title_suggestion": "暗室回声"},
        "assets": {
            "3_sheets": {"林夏": "http://img.test/lin.png", "周教授": "http://img.test/zhou.png"},
            "3_characters": [{"name": "林夏", "desc": "青灰大衣"}, {"name": "周教授", "desc": "花白头发"}],
            "2_breakdown": {
                "scenes": [
                    {"scene_id": "E1S01", "content": "林夏在办公室与周教授对峙，桌上放着录音笔", "characters": ["林夏", "周教授"], "dialogue": "林夏：你到底瞒了什么？"},
                    {"scene_id": "E1S02", "content": "周教授在办公室里与林夏再次对峙", "characters": ["周教授", "林夏"]},
                ],
                "production_assets": {
                    "scenes": [{"name": "办公室", "description": "北侧档案柜"}],
                    "props": [{"name": "录音笔", "description": "银色录音笔"}],
                },
            },
        },
        "logs": {},
        "episodes": [],
    }


def _generate(service: DramaService, task: Dict[str, Any], scene_id: str, prompts: list | None = None) -> Dict[str, Any]:
    scene = spatial_stage.breakdown_scene(task, scene_id)
    images: list = []

    def llm(model, system, user, *args, **kwargs):
        if prompts is not None:
            prompts.append(user)
        return _table(scene_id)

    def image(model, prompt, ref_images=None, **kwargs):
        images.append(prompt)
        return f"http://img.test/{scene_id}-{len(images)}.png", "meta"

    with patch.object(service.gateway, "call_llm", side_effect=llm), \
         patch.object(service.gateway, "generate_image", side_effect=image), \
         patch("app.service.drama_service.load_storyboard_elements", return_value=[]), \
         patch("app.service.drama_service.compose_nine_grid", lambda sources, path: path):
        payload = service._generate_scene_board(
            task, task["config"], scene, sys_prompt="s", storyboard_negative="", title="暗室回声",
            genre="mystery", dir_style="noir", shot_style="cinematic", guidance="",
            char_info=("林夏", "", "周教授", ""),
        )
    payload["image_prompts"] = images
    return payload


class StageFourIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.service = DramaService()
        self.task = _task()

    def test_panels_carry_sentences_measured_on_the_stage(self):
        prompts: list = []
        payload = _generate(self.service, self.task, "E1S01", prompts)

        # The table writer was told the blocking before it wrote a single row.
        self.assertIn("【空间调度", prompts[0])
        self.assertIn("林夏恒在画左、周教授恒在画右", prompts[0])

        panels = payload["storyboard"]["panels"]
        master, reverse = panels[0], panels[2]
        self.assertIn("林夏位于画面左侧三分之一的中景，朝向画面右侧", master["composition"])
        self.assertIn("周教授位于画面右侧三分之一的中景，朝向画面左侧", master["composition"])
        self.assertIn("关系轴线为林夏—周教授连线", master["action_axis"])
        self.assertIn("相距2.6米面对面", master["blocking"])
        self.assertIn("肩背虚化", reverse["composition"])
        self.assertIn("看向", reverse["eyeline"])
        self.assertEqual(panels[3]["lens_mm"], 85)
        self.assertLess(panels[0]["lens_mm"], 40)
        for panel in panels:
            self.assertNotIn("沿场景圣经指定轴线", panel["action_axis"])   # no fixed wording left
        # The image prompt is compiled from the same contract (panels render concurrently, so pick by shot).
        second = next(prompt for prompt in payload["image_prompts"] if "镜头2的首帧" in prompt)
        self.assertIn("林夏恒在画左、周教授恒在画右", second)
        self.assertIn("遮挡画面右侧约四分之一", second)

    def test_each_shot_records_its_place_and_a_measured_screen_direction(self):
        payload = _generate(self.service, self.task, "E1S01")

        shots = payload["shots"]
        self.assertEqual([shot["spatial"]["function"] for shot in shots][:3], ["establish", "over_shoulder", "over_shoulder"])
        self.assertEqual(shots[0]["spatial"]["screen_direction"], "neutral")          # the re-establishing wide
        self.assertTrue(all(shot["spatial"]["screen_direction"] == "left_to_right" for shot in shots[1:]))
        lin = next(item for item in shots[3]["spatial"]["screen"] if item["name"] == "林夏")
        zhou = next(item for item in shots[4]["spatial"]["screen"] if item["name"] == "周教授")
        self.assertEqual((facing_side(lin["facing"]), facing_side(zhou["facing"])), ("right", "left"))
        self.assertEqual(shots[5]["spatial"]["function"], "detail")
        self.assertEqual(shots[5]["spatial"]["screen"], [])

    def test_prompt_detail_reads_positions_landmarks_locks_and_checks_from_the_plan(self):
        payload = _generate(self.service, self.task, "E1S01")
        detail = payload["prompt_detail"]

        positions = detail["foundation"]["shot_visual_design"]["frame_positions"]
        self.assertEqual([(item["subject"], item["region"]) for item in positions], [("林夏", "画面左侧三分之一"), ("周教授", "画面右侧三分之一")])
        landmarks = {item["name"]: item["relative_position"] for item in detail["foundation"]["scene_and_props"]["landmarks"]}
        self.assertRegex(landmarks["录音笔"], r"位于林夏.+约\d\.\d米")
        self.assertIn("【空间圣经】", detail["foundation"]["scene_and_props"]["spatial_structure"])
        self.assertIn("林夏恒在画左", detail["foundation"]["continuity_locks"]["camera_axis"])
        checks = {item["code"]: item for item in detail["continuity_checks"]}
        self.assertTrue(checks["frame_positions_in_screen_coordinates"]["passed"])
        self.assertTrue(checks["landmarks_relative_to_character"]["passed"])
        for code in ("spatial_axis_consistent", "spatial_subjects_in_frame", "spatial_screen_sides_stable", "spatial_actor_spacing"):
            self.assertTrue(checks[code]["passed"], code)
        self.assertTrue(detail["submission_ready"])
        self.assertIn("画面坐标：林夏位于画面左侧三分之一", detail["still_prompts"][0]["prompt"])
        self.assertTrue(audit_prompt_detail(detail)["passed"])

    def test_an_error_level_spatial_failure_holds_the_scene_back_from_stage_five(self):
        payload = _generate(self.service, self.task, "E1S01")
        plan = spatial_stage.load_plan(self.task, "E1S01")
        camera = plan.camera("cam-05")
        spatial_stage.edit_plan(self.task, "E1S01", base_revision=plan.revision, operations=[
            {"op": "move_camera", "camera_id": "cam-05", "position": [camera.position[0], camera.position[1], -camera.position[2]]},
        ])
        broken = spatial_stage.load_plan(self.task, "E1S01")

        from app.core.storyboard_prompt_detail import compile_storyboard_prompt_detail
        from app.schema.production import NineGridStoryboard

        detail = compile_storyboard_prompt_detail(
            NineGridStoryboard.model_validate(payload["storyboard"]), script_text="林夏与周教授对峙", visual_style="写实",
            scene_id="E1S01", production_context={"spatial": spatial_stage.director_context(broken)},
        ).model_dump(mode="json")

        audit = audit_prompt_detail(detail)
        self.assertFalse(detail["submission_ready"])
        self.assertFalse(audit["passed"])
        self.assertIn("spatial_axis_consistent", audit["error_codes"])

    def test_the_plan_is_stored_compactly_and_teaches_both_memories(self):
        _generate(self.service, self.task, "E1S01")
        store = self.task["assets"][spatial_stage.ASSET_KEY]

        stored = store["scenes"]["E1S01"]
        self.assertEqual(len(stored["cameras"]), 9)
        self.assertTrue(all("screen" not in shot for shot in stored["shots"]))   # measurements are recomputed on load
        self.assertEqual(store["side_memory"], {"林夏": "left", "周教授": "right"})
        self.assertIn("录音笔", [item["name"] for item in store["locations"]["办公室"]])
        loaded = spatial_stage.load_plan(self.task, "E1S01")
        self.assertTrue(loaded.shot(1).screen)
        self.assertLess(len(json.dumps(stored, ensure_ascii=False)), 40_000)

    def test_the_next_scene_in_the_same_place_keeps_sides_and_set_pieces(self):
        _generate(self.service, self.task, "E1S01")
        first = spatial_stage.load_plan(self.task, "E1S01")
        moved = spatial_stage.edit_plan(self.task, "E1S01", base_revision=first.revision, operations=[
            {"op": "move_landmark", "name": "录音笔", "position": [0.4, -0.5]},
        ])
        self.assertEqual(moved.source, "edited")

        # E1S02 names 周教授 first, yet he was promised screen right one scene earlier.
        second = spatial_stage.ensure_plan(self.task, "E1S02")

        self.assertEqual(second.location_key, first.location_key)
        self.assertEqual((second.actor("林夏").screen_side, second.actor("周教授").screen_side), ("left", "right"))
        self.assertEqual(next(item for item in second.landmarks if item.name == "录音笔").position, [0.4, -0.5])

    def test_a_persons_blocking_survives_the_board_being_drawn_again(self):
        _generate(self.service, self.task, "E1S01")
        plan = spatial_stage.load_plan(self.task, "E1S01")
        spatial_stage.edit_plan(self.task, "E1S01", base_revision=plan.revision, operations=[
            {"op": "face_pair", "first": "林夏", "second": "周教授", "distance": 1.1}, {"op": "solve_camera"},
        ])

        prompts: list = []
        payload = _generate(self.service, self.task, "E1S01", prompts)

        self.assertIn("相距约1.1米", prompts[0])
        self.assertIn("相距1.1米面对面", payload["storyboard"]["panels"][0]["blocking"])
        redrawn = spatial_stage.load_plan(self.task, "E1S01")
        self.assertEqual(redrawn.source, "edited")
        self.assertTrue(all(check.passed for check in redrawn.checks if check.severity == "error"))

    def test_a_scene_the_stage_cannot_plan_is_drawn_with_the_fixed_wording_instead_of_failing(self):
        with patch("app.service.spatial_stage_service.build_plan", side_effect=ValueError("boom")):
            payload = _generate(self.service, self.task, "E1S01")

        panel = payload["storyboard"]["panels"][0]
        self.assertEqual(panel["action_axis"], "沿场景圣经指定轴线，人物不越180度轴线")
        self.assertEqual(panel["lens_mm"], 50)
        self.assertNotIn("spatial", payload["shots"][0])
        self.assertNotIn(spatial_stage.ASSET_KEY, self.task["assets"])

    def test_a_legacy_task_whose_scenes_survive_only_as_shots_still_opens(self):
        payload = _generate(self.service, self.task, "E1S01")
        self.task["assets"]["4"] = payload["shots"]
        self.task["assets"]["2_breakdown"]["scenes"] = []
        self.task["assets"].pop(spatial_stage.ASSET_KEY)

        plan = spatial_stage.ensure_plan(self.task, "E1S01")

        self.assertEqual(len(plan.cameras), 9)
        self.assertEqual({actor.name for actor in plan.actors}, {"林夏", "周教授"})
        self.assertIsNone(spatial_stage.ensure_plan(self.task, "E7S07"))

    def test_set_piece_ids_stay_unique_when_the_inherited_set_has_gaps(self):
        _generate(self.service, self.task, "E1S01")
        plan = spatial_stage.load_plan(self.task, "E1S01")
        spatial_stage.edit_plan(self.task, "E1S01", base_revision=plan.revision, operations=[
            {"op": "add_landmark", "name": "屏风", "position": [0, -3.4]},
            {"op": "remove_landmark", "name": "录音笔"},
        ])
        self.task["assets"]["2_breakdown"]["production_assets"]["props"].append({"name": "怀表", "description": "铜壳"})
        self.task["assets"]["2_breakdown"]["scenes"][1]["content"] += "，手里攥着怀表"

        second = spatial_stage.ensure_plan(self.task, "E1S02")

        ids = [item.id for item in second.landmarks]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertIn("屏风", [item.name for item in second.landmarks])

    def test_a_legacy_clip_without_a_plan_still_infers_direction_from_its_wording(self):
        self.assertEqual(spatial_stage.screen_direction(spatial_stage.ensure_plan(self.task, "E1S01"), 99), "neutral")
        self.assertIsNone(spatial_stage.ensure_plan(self.task, "E9S99"))
        self.assertEqual(spatial_stage.panel_fields(spatial_stage.ensure_plan(self.task, "E1S01"), 99), {})


class SpatialApiTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.repo = TaskRepository(str(Path(self.temp.name) / "tasks.json"))
        self.service = DramaService()
        self.service.repo = self.repo
        task = _task("spatial-api")
        payload = _generate(self.service, task, "E1S01")
        task["assets"]["4"] = payload["shots"]
        task["assets"]["4_scene_boards"] = {
            "E1S01": {"status": "done", "shots_total": 9, "shots_done": 9, "episode": 1, "prompt_detail": payload["prompt_detail"]},
            "E1S02": {"status": "pending", "shots_total": 9, "shots_done": 0, "episode": 1},
        }
        task["assets"]["5"] = [{"shot_id": 1, "image_url": payload["shots"][0]["image_url"], "video_url": "http://v/1.mp4"}]
        task["current_stage"] = 5
        self.repo.save_task("spatial-api", task)
        app.dependency_overrides[get_current_user] = lambda: {"user_id": "director-user", "role": "user"}
        self.client = TestClient(app, cookies={"auth_token": auth_service.generate_token("director-user")})

    def tearDown(self):
        self.client.close()
        app.dependency_overrides.pop(get_current_user, None)
        self.temp.cleanup()

    def _get(self, path: str):
        with patch.object(drama_api, "service", self.service):
            return self.client.get(f"/api/drama/spatial-api{path}")

    def _send(self, method: str, path: str, body: Dict[str, Any] | None = None):
        with patch.object(drama_api, "service", self.service):
            return self.client.request(method, f"/api/drama/spatial-api{path}", json=body)

    def test_overview_lists_scenes_and_memories(self):
        body = self._get("/spatial").json()

        self.assertEqual(body["schemaVersion"], "spatial-stage.v1")
        self.assertEqual([scene["sceneId"] for scene in body["scenes"]], ["E1S01"])
        self.assertEqual(body["scenes"][0]["cameraCount"], 9)
        self.assertEqual(body["scenes"][0]["errors"], [])
        self.assertEqual(body["sideMemory"], {"林夏": "left", "周教授": "right"})
        self.assertEqual(body["locations"], {"办公室": 2})

    def test_a_scene_without_a_stored_plan_is_previewed_and_nothing_is_written(self):
        stored = self._get("/spatial/scenes/E1S01").json()
        preview = self._get("/spatial/scenes/E1S02").json()
        missing = self._get("/spatial/scenes/E9S99")

        self.assertTrue(stored["persisted"])
        self.assertEqual(stored["boardStatus"], "done")
        self.assertEqual(len(stored["plan"]["shots"][0]["screen"]), 2)
        self.assertFalse(preview["persisted"])
        self.assertEqual(preview["plan"]["coverage"], "template")
        self.assertNotIn("E1S02", self.repo.get_task("spatial-api")["assets"][spatial_stage.ASSET_KEY]["scenes"])
        self.assertEqual(missing.status_code, 404)

    def test_patch_applies_semantic_edits_and_flags_the_finished_board(self):
        revision = self._get("/spatial/scenes/E1S01").json()["plan"]["revision"]
        response = self._send("PATCH", "/spatial/scenes/E1S01", {
            "baseRevision": revision,
            "operations": [
                {"op": "place_relative", "name": "周教授", "anchor": "林夏", "relation": "front", "distance": 1.2},
                {"op": "solve_camera"},
            ],
        })

        self.assertEqual(response.status_code, 200, response.text)
        body = response.json()
        self.assertEqual(body["plan"]["revision"], revision + 1)
        self.assertEqual(body["plan"]["source"], "edited")
        self.assertTrue(body["boardStale"])
        self.assertTrue(all(check["passed"] for check in body["plan"]["checks"] if check["severity"] == "error"))
        stored = self.repo.get_task("spatial-api")
        self.assertTrue(stored["assets"]["4_scene_boards"]["E1S01"]["spatial_stale"])
        self.assertEqual(stored["current_stage"], 5)   # an edit never moves the workflow

    def test_patch_rejects_a_stale_revision_a_bad_operation_and_a_running_task(self):
        revision = self._get("/spatial/scenes/E1S01").json()["plan"]["revision"]
        stale = self._send("PATCH", "/spatial/scenes/E1S01", {"baseRevision": revision + 7, "operations": [{"op": "solve_camera"}]})
        bad = self._send("PATCH", "/spatial/scenes/E1S01", {"baseRevision": revision, "operations": [{"op": "move_actor", "name": "无名氏", "position": [0, 0]}]})
        task = self.repo.get_task("spatial-api")
        task["status"] = "running"
        self.repo.save_task("spatial-api", task)
        running = self._send("PATCH", "/spatial/scenes/E1S01", {"baseRevision": revision, "operations": [{"op": "solve_camera"}]})

        self.assertEqual(stale.status_code, 409)
        self.assertEqual(bad.status_code, 422)
        self.assertIn("无名氏", bad.json()["detail"])
        self.assertEqual(running.status_code, 409)
        self.assertEqual(self.repo.get_task("spatial-api")["assets"][spatial_stage.ASSET_KEY]["scenes"]["E1S01"]["revision"], revision)

    def test_rebuild_discards_edits(self):
        revision = self._get("/spatial/scenes/E1S01").json()["plan"]["revision"]
        edited = self._send("PATCH", "/spatial/scenes/E1S01", {
            "baseRevision": revision, "operations": [{"op": "face_pair", "first": "林夏", "second": "周教授", "distance": 0.9}],
        }).json()

        rebuilt = self._send("POST", "/spatial/scenes/E1S01/rebuild", {"baseRevision": edited["plan"]["revision"]}).json()

        self.assertEqual(rebuilt["plan"]["source"], "auto")
        self.assertIn("相距2.6米", rebuilt["plan"]["formation"])
        self.assertGreater(rebuilt["plan"]["revision"], edited["plan"]["revision"])

    def test_redraw_sends_one_scene_back_to_stage_four(self):
        response = self._send("POST", "/spatial/scenes/E1S01/redraw")

        self.assertEqual(response.status_code, 200, response.text)
        stored = self.repo.get_task("spatial-api")
        board = stored["assets"]["4_scene_boards"]["E1S01"]
        self.assertEqual((board["status"], board["shots_done"]), ("pending", 0))
        self.assertEqual(stored["assets"]["4"], [])
        self.assertEqual(stored["current_stage"], 4)
        self.assertTrue(stored["assets"]["5"][0]["stale"])
        self.assertFalse(stored["assets"]["4_progress"]["episodes"][0]["complete"])
        # The blocking the scene will be drawn from is still there.
        self.assertIn("E1S01", stored["assets"][spatial_stage.ASSET_KEY]["scenes"])
        self.assertEqual(self._send("POST", "/spatial/scenes/E1S02/redraw").status_code, 200)
        self.assertEqual(self._send("POST", "/spatial/scenes/E9S99/redraw").status_code, 404)

    def test_export_and_import_round_trip_through_both_desk_formats(self):
        desk = self._get("/spatial/scenes/E1S01/export?format=director-desk").json()
        costage = self._get("/spatial/scenes/E1S01/export?format=costage").json()
        unknown = self._get("/spatial/scenes/E1S01/export?format=fbx")

        self.assertEqual(desk["document"]["version"], 1)
        self.assertEqual(desk["fileName"], "E1S01-director-desk.json")
        self.assertEqual(costage["document"]["version"], 2)
        self.assertEqual(unknown.status_code, 422)

        document = desk["document"]
        for item in document["objects"]:
            if item["name"] == "林夏":
                item["transform"]["position"] = [-2.4, 0.0, 0.3]
        revision = self._get("/spatial/scenes/E1S01").json()["plan"]["revision"]
        imported = self._send("POST", "/spatial/scenes/E1S01/import", {"baseRevision": revision, "document": document})
        refused = self._send("POST", "/spatial/scenes/E1S01/import", {"baseRevision": revision + 1, "document": {"version": 9}})

        self.assertEqual(imported.status_code, 200, imported.text)
        lin = next(actor for actor in imported.json()["plan"]["actors"] if actor["name"] == "林夏")
        self.assertEqual(lin["position"], [-2.4, 0.3])
        self.assertEqual(refused.status_code, 422)

    def test_another_users_task_is_hidden(self):
        app.dependency_overrides[get_current_user] = lambda: {"user_id": "someone-else", "role": "user"}
        self.assertEqual(self._get("/spatial").status_code, 404)
        self.assertEqual(self._get("/spatial/scenes/E1S01").status_code, 404)


