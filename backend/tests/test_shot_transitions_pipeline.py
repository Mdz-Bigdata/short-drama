# -*- coding: utf-8 -*-
"""The cut plan inside the task pipeline: the stage-4 table prompt and panels, the director's
prompt detail and continuity checks, the fallback when planning fails, and the transitions the
final film is composed with.

Only the model gateway is stubbed; boards are generated by the real ``_generate_scene_board``.
"""

import unittest
from unittest.mock import patch

from app.core.continuity_audit import audit_prompt_detail
from app.service.drama_service import DramaService, final_cut_transitions
from tests.test_spatial_stage_pipeline import _generate, _task


class StageFourCutPlanTests(unittest.TestCase):
    def setUp(self):
        self.service = DramaService()
        self.task = _task("cuts-1")

    def test_the_table_writer_is_told_how_shots_join_and_every_shot_records_the_cut_into_it(self):
        prompts: list = []
        payload = _generate(self.service, self.task, "E1S01", prompts)

        self.assertIn("【镜头衔接】", prompts[0])
        self.assertIn("时间流逝与回忆用叠化", prompts[0])

        cut_in = [shot["cut_in"] for shot in payload["shots"]]
        # The first scene of the episode fades in; inside the scene everything is a hard cut.
        self.assertEqual((cut_in[0]["from_shot"], cut_in[0]["label"], cut_in[0]["compositor"]), (0, "淡入淡出·开场", "dip_to_black"))
        self.assertTrue(all(item["compositor"] == "hard_cut" for item in cut_in[1:]))
        # 林夏 stares across the table, and the next shot is what she stares at.
        self.assertEqual(cut_in[2]["technique"], "eyeline_match")
        self.assertEqual(cut_in[3]["technique"], "shot_reverse")
        # The recorder insert is followed by a return to the people.
        self.assertEqual(cut_in[6]["technique"], "reaction")
        self.assertEqual(cut_in[3]["motion_join"], "static_to_moving")

    def test_panels_say_what_happens_at_each_cut_instead_of_one_fixed_sentence(self):
        payload = _generate(self.service, self.task, "E1S01")
        panels = payload["storyboard"]["panels"]
        shots = payload["shots"]

        self.assertIn("渐显进入", panels[0]["edit_in"])
        self.assertIn("切到对方，视线方向与上一镜相对", panels[3]["edit_in"])
        self.assertIn("先以起幅稳住约半秒再开始运动", panels[3]["edit_in"])
        self.assertIn("运镜在切点前约半秒落幅稳住再切", panels[3]["edit_out"])
        self.assertEqual(panels[3]["end_state"], "运镜落幅稳住，人物姿态与视线定格在可承接的状态")
        self.assertIn("本场最后一镜", panels[8]["edit_out"])
        self.assertGreater(len({panel["edit_in"] for panel in panels}), 4)
        self.assertIn("承接第3镜（硬切·正反打）", shots[3]["continuity_in"])
        self.assertIn("向第5镜交付", shots[3]["continuity_out"])

    def test_the_prompt_detail_carries_the_cut_summary_and_the_transition_checks(self):
        payload = _generate(self.service, self.task, "E1S01")
        detail = payload["prompt_detail"]

        linkage = detail["foundation"]["transition_design"]["internal_linkage"]
        self.assertTrue(linkage.startswith("逐镜衔接：入场→1 淡入淡出·开场；1→2 "))
        self.assertIn("2→3 硬切·视线匹配（林夏投向画外的视线）", linkage)

        checks = {item["code"]: item for item in detail["continuity_checks"]}
        for code in ("transition_shot_size_step", "transition_thirty_degree", "transition_state_continuous",
                     "transition_eyeline_answered", "transition_cause_before_effect", "transition_light_continuity"):
            self.assertTrue(checks[code]["passed"], code)
        # The stub table gives every shot three seconds: flagged, but only as a warning.
        self.assertFalse(checks["transition_rhythm"]["passed"])
        self.assertEqual(checks["transition_rhythm"]["severity"], "warning")
        self.assertTrue(detail["submission_ready"])
        self.assertTrue(audit_prompt_detail(detail)["passed"])

    def test_a_later_scene_of_the_same_episode_cuts_from_the_scene_before_it(self):
        first = _generate(self.service, self.task, "E1S01")
        self.task["assets"]["4"] = first["shots"]

        second = _generate(self.service, self.task, "E1S02")

        opening = second["shots"][0]["cut_in"]
        self.assertEqual((opening["kind"], opening["technique"], opening["compositor"]), ("cut", "scene_change", "hard_cut"))
        self.assertIn("入场→1 硬切·场景转换", second["prompt_detail"]["foundation"]["transition_design"]["internal_linkage"])

    def test_a_scene_whose_cuts_cannot_be_planned_keeps_the_fixed_wording_instead_of_failing(self):
        with patch("app.core.shot_transitions.plan_transitions", side_effect=RuntimeError("boom")):
            payload = _generate(self.service, self.task, "E1S01")

        panel = payload["storyboard"]["panels"][1]
        self.assertEqual(panel["edit_in"], "承接上一格动作、视线或声音桥，在叙事信息可读后切入")
        self.assertEqual(panel["edit_out"], "在动作接触、视线落点、情绪转折或对白收音点切出")
        self.assertNotIn("cut_in", payload["shots"][0])
        self.assertIn("spatial", payload["shots"][0])        # the spatial stage is unaffected
        detail = payload["prompt_detail"]
        self.assertFalse(detail["foundation"]["transition_design"]["internal_linkage"].startswith("逐镜衔接"))
        codes = {item["code"] for item in detail["continuity_checks"]}
        self.assertFalse(codes & {"transition_shot_size_step", "transition_state_continuous", "transition_rhythm"})
        self.assertIn("transition_types_in_catalog", codes)       # the compiler's own check is still there


def _state(**overrides):
    state = {
        "characters": ["林夏", "周教授"], "scene": "E1S01", "screen_direction": "left_to_right",
        "action": "对峙", "emotion": "紧张", "props": {"录音笔": "林夏"}, "lighting": "冷白顶光", "audio_bed": "办公室空调声",
    }
    state.update(overrides)
    return state


def _clip(shot_id, cut_in=None, **state):
    clip = {"shot_id": shot_id, "continuity_state": _state(**state)}
    if cut_in is not None:
        clip["cut_in"] = cut_in
    return clip


class FinalCutTransitionTests(unittest.TestCase):
    def test_the_film_is_cut_the_way_stage_four_planned_once_the_continuity_gate_passes(self):
        clips = [
            _clip(1),
            _clip(2, {"label": "硬切·正反打", "compositor": "hard_cut", "duration_seconds": 0.0}),
            _clip(3, {"label": "叠化·时间流逝", "compositor": "crossfade", "duration_seconds": 0.5}),
            _clip(4, {"label": "淡入淡出·章节转换", "compositor": "dip_to_black", "duration_seconds": 0.8}),
        ]
        specs, reports = final_cut_transitions(clips)

        self.assertEqual([spec["type"] for spec in specs], ["hard_cut", "crossfade", "dip_to_black"])
        self.assertEqual([spec["duration"] for spec in specs[1:]], [0.5, 0.8])
        self.assertEqual([report["planned_cut"] for report in reports], ["硬切·正反打", "叠化·时间流逝", "淡入淡出·章节转换"])
        self.assertTrue(all(report["accepted"] for report in reports))

    def test_a_cut_without_a_plan_uses_the_gate_s_own_choice(self):
        specs, reports = final_cut_transitions([_clip(1), _clip(2), _clip(3, {"compositor": "wipe"})])
        self.assertEqual([spec["type"] for spec in specs], ["hard_cut", "hard_cut"])
        self.assertNotIn("planned_cut", reports[0])
        self.assertNotIn("planned_cut", reports[1])

        legacy, notes = final_cut_transitions([{"shot_id": 1}, {"shot_id": 2}])
        self.assertEqual(legacy, [{"type": "crossfade", "duration": 0.22}])
        self.assertIn("缺少旧任务结构化状态", notes[0]["reasons"][0])

    def test_a_planned_dissolve_does_not_smuggle_a_crossed_axis_into_the_film(self):
        clips = [
            _clip(1),
            _clip(2, {"label": "叠化·时间流逝", "compositor": "crossfade", "duration_seconds": 0.5}, screen_direction="right_to_left"),
        ]
        with self.assertRaisesRegex(RuntimeError, "镜头 1→2 连续性质检失败"):
            final_cut_transitions(clips)


if __name__ == "__main__":
    unittest.main()
